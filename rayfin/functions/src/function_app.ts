import {
  UserDataFunctions,
  AudienceType,
  type RayfinContext,
} from '@microsoft/fabric-user-data-functions';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';

const udf = new UserDataFunctions();

const MAX_QUESTION_LENGTH = 2000;
// Function execution limit is 240s; leave headroom to return a clean error.
const REQUEST_TIMEOUT_MS = 200_000;

const FABRIC_MCP_URL_PATTERN =
  /^https:\/\/api\.fabric\.microsoft\.com\/v1\/mcp\/workspaces\/[0-9a-f-]{36}\/dataagents\/[0-9a-f-]{36}\/agent$/i;

/** Only send the Fabric token to a published data agent endpoint on api.fabric.microsoft.com. */
function readAgentUrl(ctx: RayfinContext<Record<string, any>, AudienceType.Fabric>): URL {
  const configured = ctx.getSecret('DATA_AGENT_MCP_URL');
  if (!configured) {
    throw new Error(
      "The data agent isn't configured. Set the DATA_AGENT_MCP_URL secret with `npx rayfin secret set DATA_AGENT_MCP_URL`.",
    );
  }
  if (!FABRIC_MCP_URL_PATTERN.test(configured)) {
    throw new Error(
      'DATA_AGENT_MCP_URL must look like https://api.fabric.microsoft.com/v1/mcp/workspaces/{workspaceId}/dataagents/{dataAgentId}/agent.',
    );
  }
  return new URL(configured);
}

/**
 * A simple greeting function.
 *
 * The input/output types for this function are autogenerated in ./types.ts so that
 * RayfinClient can invoke it with full type-safety from your frontend app.
 */
udf.func('helloWorld', (firstName: string, lastName: string): string => {
  console.log(`helloWorld invoked for ${firstName} ${lastName}`);
  return `Hello ${firstName} ${lastName}!`;
}, []);

/**
 * Asks the published Fabric data agent a natural-language question.
 *
 * Runs as the app identity (the owner of the Fabric app item), so every signed-in
 * app user sees answers based on that identity's access to the agent's data sources.
 */
udf.func(
  'askDataAgent',
  async (
    question: string,
    ctx: RayfinContext<Record<string, any>, AudienceType.Fabric>,
  ): Promise<string> => {
    const trimmed = (question ?? '').trim();
    if (!trimmed) {
      throw new Error('Enter a question for the data agent.');
    }
    if (trimmed.length > MAX_QUESTION_LENGTH) {
      throw new Error(`Questions are limited to ${MAX_QUESTION_LENGTH} characters.`);
    }

    const url = readAgentUrl(ctx);
    const transport = new StreamableHTTPClientTransport(url, {
      requestInit: { headers: { Authorization: `Bearer ${ctx.Tokens.Fabric}` } },
    });
    const client = new Client({ name: 'rayfin-app', version: '1.0.0' });

    try {
      await client.connect(transport);

      // The data agent exposes one tool; read its question argument from the input schema.
      const { tools } = await client.listTools();
      const tool = tools[0];
      if (!tool) {
        throw new Error('The data agent did not advertise a tool. Check that it is published.');
      }
      const questionArg = Object.keys(tool.inputSchema.properties ?? {})[0];
      if (!questionArg) {
        throw new Error("The data agent's tool does not accept a question argument.");
      }

      const result = await client.callTool(
        { name: tool.name, arguments: { [questionArg]: trimmed } },
        undefined,
        { timeout: REQUEST_TIMEOUT_MS },
      );

      const blocks = Array.isArray(result.content) ? result.content : [];
      const answer = blocks
        .filter((b): b is { type: 'text'; text: string } => b?.type === 'text' && typeof b.text === 'string')
        .map((b) => b.text)
        .join('\n')
        .trim();

      if (result.isError) {
        throw new Error(answer || 'The data agent returned an error.');
      }
      if (!answer) {
        throw new Error('The data agent returned no answer.');
      }
      return answer;
    } finally {
      await client.close().catch(() => undefined);
    }
  },
  [],
);
